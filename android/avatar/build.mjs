#!/usr/bin/env node
// Builds the avatar editor page for both apps from one source:
//   editor.src.html            the page (edit this one)
//   vendor/*.mjs               Humation's code, MIT (see vendor/LICENSE-Humation.txt)
//   parts/<slot>/<name>.svg    REAL's own parts (see parts/README.md)
// Output: the Android asset and the iOS resource, same bytes. Run from anywhere: node android/avatar/build.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const outputs = [
  join(repo, 'android', 'app', 'src', 'main', 'assets', 'avatar', 'editor.html'),
  join(repo, 'ios', 'Real', 'Resources', 'Avatar', 'avatar-editor.html')
];
const modules = [
  ['hm-core', 'humation-core-1.0.3.mjs'],
  ['hm-assets', 'humation-assets-humation-1-1.0.3.mjs']
];
// Layer sizes from Humation 1's manifest; a REAL part must match its slot so it lines up with the body.
const SLOTS = { head: [80, 80], body: [80, 80], bottom: [80, 107], item: [80, 80], glasses: [80, 80] };
const PLACEHOLDERS = ['__SAVED_STATE__', '__TOP_INSET__', '__UNLOCKED__'];

function fail(message) { console.error('avatar build: ' + message); process.exit(1); }

// Text that would end the <script> element early or collide with the app's placeholders cannot be inlined.
function inlineSafe(text, label) {
  if (/<\/script/i.test(text) || text.includes('<!--')) fail(`${label} contains "</script" or "<!--"`);
  for (const p of PLACEHOLDERS) if (text.includes(p)) fail(`${label} contains the placeholder ${p}`);
  return text;
}

function realParts() {
  const parts = [];
  for (const [slot, [w, h]] of Object.entries(SLOTS)) {
    const dir = join(here, 'parts', slot);
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
      const name = file.slice(0, -4);
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) fail(`parts/${slot}/${file}: use lowercase letters, digits and dashes`);
      const svg = readFileSync(join(dir, file), 'utf8').replace(/^﻿/, '').replace(/<\?xml[^>]*\?>\s*/, '').trim();
      if (!svg.startsWith('<svg')) fail(`parts/${slot}/${file}: not an SVG`);
      if (/<script|\son[a-z]+\s*=|javascript:|<foreignObject|<image|href\s*=\s*["']https?:/i.test(svg)) {
        fail(`parts/${slot}/${file}: scripts, event handlers, embedded images and external links are not allowed`);
      }
      const box = /viewBox\s*=\s*["']\s*0\s+0\s+([\d.]+)\s+([\d.]+)\s*["']/.exec(svg);
      if (!box || Number(box[1]) !== w || Number(box[2]) !== h) {
        fail(`parts/${slot}/${file}: viewBox must be "0 0 ${w} ${h}" for the ${slot} slot`);
      }
      if (!svg.includes('var(--hm-')) console.warn(`avatar build: parts/${slot}/${file} uses no var(--hm-…) colour; the colour picker will not change it`);
      inlineSafe(svg, `parts/${slot}/${file}`);
      parts.push({
        id: `real-p-${slot}-${name}`,
        name: `real-${name}`,
        // Sorts after Humation's own parts ("001"…) in the picker.
        source: { groupId: slot, sourceGroupName: 'REAL', partId: `zz-${name}` },
        selectionSlot: slot,
        uiGroups: [slot],
        layers: [{ layerSlot: slot, svg }]
      });
    }
  }
  return parts;
}

let page = readFileSync(join(here, 'editor.src.html'), 'utf8');
const modulesMarker = '<!--@HUMATION_MODULES@-->';
const partsMarker = '/*@REAL_PARTS@*/[]';
if (page.split(modulesMarker).length !== 2) fail('editor.src.html needs exactly one ' + modulesMarker);
if (page.split(partsMarker).length !== 2) fail('editor.src.html needs exactly one ' + partsMarker);

const inlined = modules.map(([id, file]) => {
  const code = inlineSafe(readFileSync(join(here, 'vendor', file), 'utf8'), 'vendor/' + file);
  return `<script type="text/plain" id="${id}">\n${code}\n</script>`;
}).join('\n');
const parts = realParts();
// "<" escaped so an SVG string can never close the script element.
const partsJson = JSON.stringify(parts).replace(/</g, '\\u003c');

page = page.replace(modulesMarker, () => `<!-- Generated by android/avatar/build.mjs. Humation 1.0.3, MIT License, Copyright (c) 2026 Humation contributors. -->\n${inlined}`)
  .replace(partsMarker, () => partsJson);

for (const out of outputs) writeFileSync(out, page);
console.log(`avatar build: ${parts.length} REAL part(s), ${Math.round(page.length / 1024)} KB → ${outputs.length} files`);
